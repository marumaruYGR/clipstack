@_silgen_name("stack_command") private func stackCommand(_ command: UnsafePointer<CChar>) -> UnsafeMutablePointer<CChar>
@_silgen_name("stack_free") private func stackFree(_ value: UnsafeMutablePointer<CChar>)
@_silgen_name("stack_index_text")
private func stackIndexText(_ id: UnsafePointer<CChar>, _ text: UnsafePointer<UInt8>?, _ length: Int)

struct ClipSearchResults {
    let history: [Clip]
    let favorites: [Clip]
}

struct Clip: Codable, Identifiable, Equatable, Sendable {
    var id = UUID()
    var date = Date()
    var items: [[String: Data]]
    var portableContent: PortableContent?

    func data(_ type: NSPasteboard.PasteboardType) -> Data? {
        items.lazy.compactMap { $0[type.rawValue] }.first
    }

    var files: [ClipboardFile] {
        items.compactMap { Self.fileURL(in: $0).map(ClipboardFile.init) }
    }

    private static func fileURL(in item: [String: Data]) -> URL? {
        for type in [NSPasteboard.PasteboardType.fileURL, .URL] {
            if let data = item[type.rawValue], let text = String(data: data, encoding: .utf8),
               let url = URL(string: text), url.isFileURL, url.path.hasPrefix("/"),
               url.host == nil || url.host == "" || url.host == "localhost" {
                return url
            }
        }
        return nil
    }

    static func fileReferences(_ urls: [URL]) -> Clip {
        Clip(items: urls.map { [NSPasteboard.PasteboardType.fileURL.rawValue: Data($0.absoluteString.utf8)] })
    }

    var text: String {
        let files = files
        if let first = files.first { return files.count == 1 ? first.name : "\(first.name) 等 \(files.count) 个文件" }
        if let paths = portableContent?.paths, let first = paths.first {
            let name = first.split(whereSeparator: { $0 == "/" || $0 == "\\" }).last.map(String.init) ?? first
            return paths.count == 1 ? name : "\(name) 等 \(paths.count) 个文件"
        }
        if let plain = data(.string), let text = String(data: plain, encoding: .utf8) { return text }
        if let url = data(.URL), let text = String(data: url, encoding: .utf8) { return text }
        return image == nil ? "富文本" : "图片"
    }

    var image: NSImage? { (data(.png) ?? data(.tiff)).flatMap(NSImage.init(data:)) }
    var kind: String {
        let files = files
        if let first = files.first { return files.count == 1 ? first.kind.label : "文件" }
        if portableContent?.kind == "files" { return "文件" }
        if image != nil { return "图片" }
        if data(.rtf) != nil || data(.html) != nil || data(.rtfd) != nil { return "富文本" }
        let scheme = URL(string: text.trimmingCharacters(in: .whitespacesAndNewlines))?.scheme
        return scheme == "https" || scheme == "http" || data(.URL) != nil ? "链接" : "文字"
    }

    var symbol: String {
        let files = files
        if let first = files.first { return files.count == 1 ? first.kind.symbol : "doc.on.doc" }
        switch kind {
        case "图片": return "photo"
        case "链接": return "link"
        default: return "text.alignleft"
        }
    }
    static func manual(_ string: String) -> Clip {
        Clip(items: [[NSPasteboard.PasteboardType.string.rawValue: Data(string.utf8)]])
    }

    static func read(_ board: NSPasteboard) -> Clip? {
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        guard !(board.types ?? []).contains(where: { excluded.contains($0.rawValue) }) else { return nil }
        let allowed: Set<NSPasteboard.PasteboardType> = [.fileURL, .string, .URL, .rtf, .rtfd, .html, .png, .tiff]
        let items = (board.pasteboardItems ?? []).compactMap { item -> [String: Data]? in
            let representations = item.types.filter { allowed.contains($0) }.compactMap { type in
                item.data(forType: type).map { (type.rawValue, $0) }
            }
            return representations.isEmpty ? nil : Dictionary(uniqueKeysWithValues: representations)
        }
        let urls = items.compactMap(Self.fileURL)
        if !urls.isEmpty { return .fileReferences(urls) }
        let legacyFileList = NSPasteboard.PasteboardType("NSFilenamesPboardType")
        if board.types?.contains(legacyFileList) == true,
           let paths = board.propertyList(forType: legacyFileList) as? [String] {
            let urls = paths.filter { $0.hasPrefix("/") }.map { URL(fileURLWithPath: $0) }
            if !urls.isEmpty { return .fileReferences(urls) }
        }
        return items.isEmpty ? nil : Clip(items: items)
    }

    func write(_ board: NSPasteboard) -> Bool {
        let files = files
        if !files.isEmpty {
            board.clearContents()
            return board.writeObjects(files.map { $0.url as NSURL })
        }
        let objects = items.map { properties in
            let item = NSPasteboardItem()
            for (type, content) in properties { item.setData(content, forType: .init(type)) }
            return item
        }
        board.clearContents()
        return board.writeObjects(objects)
    }
}

@MainActor final class Store: ObservableObject {
    @Published private(set) var history: [Clip] = []
    @Published private(set) var favorites: [Clip] = []
    @Published var selection: Set<UUID> = []
    @Published var error: String?
    @Published var favoriteURL: URL
    @Published private(set) var favoriteProblem: String?
    private var previousCount = NSPasteboard.general.changeCount
    private var clips: [UUID: Clip] = [:]
    private var indexedClips: Set<UUID> = []
    private var lastSearch: (query: String, results: ClipSearchResults)?
    private let historyURL: URL
    private var favoriteReady = true
    private var favoritesKeyName = UserDefaults.standard.string(forKey: "favoritesKeyName") ?? "favorites"

    init() {
        let files = FileManager.default
        let base = LoginSession.storageDirectory
        historyURL = base.appending(path: "History-\(LoginSession.historyName).bin")
        favoriteURL = UserDefaults.standard.url(forKey: "favoritesURL")
            ?? files.urls(for: .documentDirectory, in: .userDomainMask)[0].appending(path: "剪栈收藏夹.favorites")
        if let restored = try? load(historyURL, key: "history") { restore(restored, action: "push") }
        do { restore(try load(favoriteURL, key: favoritesKeyName), action: "save") }
        catch {
            favoriteReady = false
            favoriteProblem = "无法读取原收藏夹，可从加密备份恢复到新目录。\(error.localizedDescription)"
            self.error = favoriteProblem
        }
        refresh()
        try? (base as NSURL).setResourceValue(true, forKey: .isExcludedFromBackupKey)
    }

    private func command(_ command: String) -> String {
        command.withCString {
            let result = stackCommand($0)
            defer { stackFree(result) }
            return String(cString: result)
        }
    }

    private func restore(_ entries: [Clip], action: String) {
        for clip in entries.reversed() {
            clips[clip.id] = clip
            _ = command("\(action) \(clip.id.uuidString)")
        }
    }

    private func refresh() {
        let refreshedHistory = entries(command("history"))
        let refreshedFavorites = entries(command("favorites"))
        let live = Set((refreshedHistory + refreshedFavorites).map(\.id))
        indexedClips.formIntersection(live)
        lastSearch = nil
        clips = clips.filter { live.contains($0.key) }
        history = refreshedHistory
        favorites = refreshedFavorites
        selection.formIntersection(Set(history.map(\.id)))
    }

    private func entries(_ ids: String) -> [Clip] {
        ids.split(separator: ",").compactMap { UUID(uuidString: String($0)).flatMap { clips[$0] } }
    }

    func search(_ query: String) -> ClipSearchResults {
        let normalized = foldedSearchText(query)
        guard !normalized.isEmpty else { return ClipSearchResults(history: history, favorites: favorites) }
        if let cache = lastSearch, cache.query == normalized { return cache.results }
        for clip in clips.values where indexedClips.insert(clip.id).inserted {
            let text = Data(foldedSearchText(clip.searchableText).utf8)
            clip.id.uuidString.withCString { id in
                text.withUnsafeBytes { bytes in
                    stackIndexText(id, bytes.baseAddress?.assumingMemoryBound(to: UInt8.self), bytes.count)
                }
            }
        }
        let lines = command("search \(normalized)").components(separatedBy: "\n")
        let results = ClipSearchResults(history: entries(lines[0]), favorites: entries(lines[1]))
        lastSearch = (normalized, results)
        return results
    }

    func poll() -> Bool {
        let board = NSPasteboard.general
        let count = board.changeCount
        guard count != previousCount else { return false }
        previousCount = count
        guard let clip = Clip.read(board) else { return false }
        add(clip)
        return true
    }

    func use(_ clip: Clip) -> Bool {
        let board = NSPasteboard.general
        let success = clip.write(board)
        previousCount = board.changeCount
        return success
    }

    func add(_ value: Clip) {
        var clip = value
        if let existing = (history + favorites).first(where: { $0.items == clip.items }) {
            clip.id = existing.id
        }
        clips[clip.id] = clip
        _ = command("push \(clip.id)")
        refresh()
        persistHistory()
    }

    func remove(_ ids: Set<UUID>) {
        _ = command("remove \(ids.map(\.uuidString).joined(separator: ","))")
        refresh()
        persistHistory()
    }

    @discardableResult func clear(_ board: NSPasteboard = .general) -> Bool {
        board.clearContents()
        let count = board.changeCount
        guard board.pasteboardItems?.isEmpty != false, board.changeCount == count else {
            error = "无法清空系统剪贴板，请重试。"
            return false
        }
        previousCount = count
        do { try save([], to: historyURL, key: "history") }
        catch {
            self.error = "系统剪贴板已清空，历史文件写入失败，请重试。\(error.localizedDescription)"
            return false
        }
        _ = command("clear")
        refresh()
        return true
    }

    func isFavorite(_ clip: Clip) -> Bool { favorites.contains { $0.id == clip.id } }

    func toggleFavorite(_ clip: Clip) {
        guard favoriteReady else { error = "收藏夹不可写，请检查文件和钥匙串访问权限。"; return }
        let removing = isFavorite(clip)
        let updated = removing ? favorites.filter { $0.id != clip.id } : [clip] + favorites
        do {
            try save(updated, to: favoriteURL, key: favoritesKeyName)
            if !removing { clips[clip.id] = clip }
            _ = command("\(removing ? "unsave" : "save") \(clip.id)")
            refresh()
        } catch { self.error = "无法保存收藏夹。\(error.localizedDescription)" }
    }

    func moveFavorites(to newURL: URL) -> Bool {
        guard favoriteReady else { error = "请先恢复原收藏夹的访问权限。"; return false }
        if newURL.standardizedFileURL == favoriteURL.standardizedFileURL { return false }
        do {
            if !FileManager.default.fileExists(atPath: favoriteURL.path) {
                try save(favorites, to: favoriteURL, key: favoritesKeyName)
            }
            try FileManager.default.moveItem(at: favoriteURL, to: newURL)
            UserDefaults.standard.set(newURL, forKey: "favoritesURL")
            favoriteURL = newURL
            return true
        } catch { self.error = "无法移动收藏夹。\(error.localizedDescription)"; return false }
    }

    func endSession() { try? FileManager.default.removeItem(at: historyURL) }

    func favoritesForBackup() throws -> [Clip] {
        guard favoriteReady else { throw ClipstackError("请先恢复原收藏夹的访问权限，或导入已有备份。") }
        return favorites
    }

    func importFavorites(_ imported: [Clip]) throws -> (added: Int, skipped: Int, recovered: URL?) {
        let existing = try? load(favoriteURL, key: favoritesKeyName)
        let needsRecovery = !favoriteReady || existing == nil
        var merged = existing ?? favorites
        var fingerprints = Set(merged.map(\.contentFingerprint))
        var additions: [Clip] = []
        for var clip in imported where fingerprints.insert(clip.contentFingerprint).inserted {
            clip.id = UUID()
            additions.append(clip)
        }
        merged.append(contentsOf: additions)
        var recovered: URL?
        if needsRecovery {
            let folder = FileManager.default.urls(for: .documentDirectory, in: .userDomainMask)[0]
                .appending(path: "剪栈/恢复的收藏-\(UUID().uuidString)")
            let destination = folder.appending(path: "剪栈收藏夹.favorites")
            let keyName = "favorites-\(UUID().uuidString)"
            try save(merged, to: destination, key: keyName)
            UserDefaults.standard.set(destination, forKey: "favoritesURL")
            UserDefaults.standard.set(keyName, forKey: "favoritesKeyName")
            favoriteURL = destination
            favoritesKeyName = keyName
            recovered = destination
        } else if !additions.isEmpty {
            try save(merged, to: favoriteURL, key: favoritesKeyName)
        }
        for clip in favorites { _ = command("unsave \(clip.id)") }
        restore(merged, action: "save")
        favoriteReady = true
        favoriteProblem = nil
        error = nil
        refresh()
        return (additions.count, imported.count - additions.count, recovered)
    }

    private func persistHistory() {
        do { try save(history, to: historyURL, key: "history") }
        catch { if self.error == nil { self.error = "无法写入本次登录的记录。\(error.localizedDescription)" } }
    }

    private func key(_ name: String, create: Bool) throws -> SymmetricKey {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword, kSecAttrService as String: "local.jianzhan.clipboard",
            kSecAttrAccount as String: name
        ]
        var item: CFTypeRef?
        var status = SecItemCopyMatching(query.merging([kSecReturnData as String: true]) { _, value in value } as CFDictionary, &item)
        if status == errSecSuccess, let data = item as? Data { return SymmetricKey(data: data) }
        if status == errSecItemNotFound && create {
            let newKey = SymmetricKey(size: .bits256)
            status = SecItemAdd(query.merging([kSecValueData as String: newKey.withUnsafeBytes { Data($0) }]) { _, value in value } as CFDictionary, nil)
            if status == errSecSuccess { return newKey }
        }
        throw NSError(domain: NSOSStatusErrorDomain, code: Int(status))
    }

    private func load(_ url: URL, key name: String) throws -> [Clip] {
        guard FileManager.default.fileExists(atPath: url.path) else { return [] }
        let box = try AES.GCM.SealedBox(combined: Data(contentsOf: url))
        let data = try AES.GCM.open(box, using: key(name, create: false))
        return try PropertyListDecoder().decode([Clip].self, from: data)
    }

    private func save(_ clips: [Clip], to url: URL, key name: String) throws {
        try FileManager.default.createDirectory(at: url.deletingLastPathComponent(), withIntermediateDirectories: true)
        let encoder = PropertyListEncoder()
        encoder.outputFormat = .binary
        let data = try encoder.encode(clips)
        let box = try AES.GCM.seal(data, using: key(name, create: true))
        guard let combined = box.combined else { throw CocoaError(.fileWriteUnknown) }
        try combined.write(to: url, options: .atomic)
        try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
    }
}
